// Generates the built-in function name list from Databricks' reference (design §5.2), and checks the committed copy.
//   node scripts/generate-allowlist.mjs           write src/domain/builtins.generated.ts from grammar/databricks/builtins.tsv
//   node scripts/generate-allowlist.mjs --check   fail when the committed file differs from a fresh generation (npm run check)
//   node scripts/generate-allowlist.mjs --fetch   refresh grammar/databricks/builtins.tsv from the live reference (by hand,
//                                                 at release; a person reviews the diff and src/domain/functions.ts)
//
// The generated file lists every name; src/domain/functions.ts (hand-written, reviewed) takes the exclusions away, so
// the allowlist is "every built-in at the pin, minus the named exclusions". A built-in added after the pin is not on
// the list, so it needs a plan.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const source = join(root, "grammar", "databricks", "builtins.tsv")
const target = join(root, "src", "domain", "builtins.generated.ts")
const URL_ALPHA = "https://docs.databricks.com/aws/en/sql/language-manual/sql-ref-functions-builtin-alpha"
/** Reference entries that are syntax, not callable names. */
const SYNTAX = new Set(["and", "or", "not", "in", "is", "case", "div"])

function generate() {
  const text = readFileSync(source, "utf8")
  const header = text.split("\n").filter((line) => line.startsWith("#"))
  const entries = text
    .split("\n")
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const [name, kinds] = line.split("\t")
      if (!/^[a-z_][a-z0-9_]*$/.test(name)) throw new Error(`builtins.tsv: ${JSON.stringify(name)} is not a function name`)
      return { name, kinds: kinds.split("; ") }
    })
  const names = entries.filter((entry) => !SYNTAX.has(entry.name))
  const tvf = names.filter((entry) => entry.kinds.some((kind) => /table-valued|table function|generator/.test(kind))).map((entry) => entry.name)
  const digest = createHash("sha256").update(text).digest("hex")
  return [
    "// GENERATED by scripts/generate-allowlist.mjs from grammar/databricks/builtins.tsv: do not edit.",
    ...header.map((line) => `// ${line.slice(1).trim()}`),
    `// builtins.tsv sha256: ${digest}`,
    "",
    "/** Every callable built-in name in the reference at the pin. src/domain/functions.ts removes the exclusions. */",
    `export const BUILTIN_NAMES: readonly string[] = ${JSON.stringify(names.map((entry) => entry.name), null, 0).replaceAll('","', '", "')}`,
    "",
    "/** The built-ins the reference calls table-valued, table or generator functions. */",
    `export const BUILTIN_TABLE_FUNCTIONS: readonly string[] = ${JSON.stringify(tvf).replaceAll('","', '", "')}`,
    "",
  ].join("\n")
}

async function fetchReference() {
  const response = await fetch(URL_ALPHA, { headers: { "User-Agent": "opencode-databricks allowlist" } })
  if (!response.ok) throw new Error(`${URL_ALPHA}: HTTP ${response.status}`)
  const html = await response.text()
  const rows = new Map()
  const unescape = (value) => value.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&amp;/g, "&")
  for (const match of html.matchAll(/href=([^ >]*functions\/[a-z0-9_]+)[^>]*>(.*?)<\/a>/g)) {
    const text = unescape(match[2].replace(/<[^>]+>/g, "")).trim()
    const entry = /^([a-z_][a-z0-9_]*)\s*(.*)$/.exec(text)
    if (!entry) continue
    if (!rows.has(entry[1])) rows.set(entry[1], new Set())
    rows.get(entry[1]).add(entry[2] || "function")
  }
  const lines = [
    "# Databricks SQL built-in functions, from the alphabetical reference (design [37]).",
    `# Source: ${URL_ALPHA}`,
    `# Fetched: ${new Date().toISOString().slice(0, 10)}. Page sha256: ${createHash("sha256").update(html).digest("hex")}`,
    "# One name per line, then the kinds the reference gives it. Refresh with: node scripts/generate-allowlist.mjs --fetch",
    "# (a person reviews the diff, then the exclusions in src/domain/functions.ts).",
    ...[...rows.keys()].sort().map((name) => `${name}\t${[...rows.get(name)].sort().join("; ")}`),
  ]
  writeFileSync(source, `${lines.join("\n")}\n`)
  console.log(`wrote grammar/databricks/builtins.tsv: ${rows.size} names. Review the diff before committing.`)
}

if (process.argv.includes("--fetch")) await fetchReference()
else if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generate()) {
    console.error("generate-allowlist: src/domain/builtins.generated.ts differs from grammar/databricks/builtins.tsv. Run node scripts/generate-allowlist.mjs and commit the result.")
    process.exit(1)
  }
  console.log("src/domain/builtins.generated.ts matches grammar/databricks/builtins.tsv.")
} else {
  writeFileSync(target, generate())
  console.log("generated src/domain/builtins.generated.ts.")
}
