// Generates the plugin's SQL parser from Spark's pinned grammar (design §5.3), and checks that the committed copy is
// exactly what generation gives.
//   node scripts/generate-parser.mjs          regenerate src/sql/generated/ from grammar/spark/
//   node scripts/generate-parser.mjs --check  regenerate into a temporary folder and fail on any difference (npm run check)
//
// Steps, all offline and deterministic:
// 1. grammar/spark/*.g4 must have exactly the sha256 recorded in grammar/spark/PIN.json, the files of Apache Spark's
//    tag named there, copied byte for byte.
// 2. grammar/port.mjs replaces each Java action and predicate with its TypeScript port, failing on any count that
//    differs (a new pin needs a person to port it), and on any Java left over.
// 3. antlr-ng (a devDependency, pinned exactly; the ANTLR tool written in TypeScript, so no Java is needed to build)
//    writes the TypeScript lexer and parser for the antlr4ng runtime (a devDependency, pinned exactly). Only the two
//    .ts files are kept; no listener or visitor is generated.
// 4. Each file gets a fixed header naming the pin and the tool versions, and nothing that varies between machines.
//
// The generated files and the antlr4ng runtime are bundled into dist/index.js by esbuild: the package still has no
// runtime dependency, and NOTICE carries antlr4ng's licence and Spark's (scripts/build.mjs).
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { LEFTOVER_JAVA, PORT } from "../grammar/port.mjs"

const root = fileURLToPath(new URL("../", import.meta.url))
const grammarDir = join(root, "grammar", "spark")
const outDir = join(root, "src", "sql", "generated")
const FILES = ["SqlBaseLexer.ts", "SqlBaseParser.ts"]
const pin = JSON.parse(readFileSync(join(grammarDir, "PIN.json"), "utf8"))
const version = (name) => JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8")).version

function fail(message) {
  console.error(`generate-parser: ${message}`)
  process.exit(1)
}

const sha256 = (text) => createHash("sha256").update(text).digest("hex")

function ported(file) {
  const text = readFileSync(join(grammarDir, file), "utf8")
  if (sha256(text) !== pin.files[file]) fail(`grammar/spark/${file} is not the pinned file (sha256 ${pin.files[file]}). Copy it again from ${pin.repository} at ${pin.commit}.`)
  let out = text
  for (const entry of PORT.filter((item) => item.file === file)) {
    const pattern = typeof entry.java === "string" ? new RegExp(entry.java.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g") : new RegExp(entry.java.source, "g")
    const found = out.match(pattern)?.length ?? 0
    if (found !== entry.count) fail(`${file}: expected ${entry.count} of ${JSON.stringify(String(entry.java)).slice(0, 80)} (${entry.why}), found ${found}. Port the grammar's actions again in grammar/port.mjs.`)
    out = out.replace(pattern, () => entry.ts)
  }
  for (const leftover of LEFTOVER_JAVA) {
    const match = leftover.exec(out)
    if (match) fail(`${file}: Java is left after the port: ${JSON.stringify(match[0])}. Add it to grammar/port.mjs.`)
  }
  return out
}

/**
 * The parser's vocabulary is the lexer's, token for token: antlr-ng writes the same `literalNames` and
 * `symbolicNames` arrays into both files, so the parser refers to the lexer's arrays instead of bundling a second
 * copy (about 13 KB of needless repeated text in dist/index.js). The values and the parser's `Vocabulary` stay
 * exactly as they were.
 */
function shareVocabulary(files) {
  const lexer = files["SqlBaseLexer.ts"]
  let parser = files["SqlBaseParser.ts"]
  for (const field of ["literalNames", "symbolicNames"]) {
    const array = (text) => new RegExp(`    public static readonly ${field} = \\[[\\s\\S]*?\\n    \\];`).exec(text)?.[0]
    const own = array(parser)
    const shared = array(lexer)
    if (own === undefined || shared === undefined) fail(`SqlBaseParser.ts or SqlBaseLexer.ts has no ${field} array; the parser vocabulary cannot be shared.`)
    if (own !== shared) fail(`SqlBaseParser.ts and SqlBaseLexer.ts name different ${field} values; review the share in scripts/generate-parser.mjs.`)
    parser = parser.replace(own, `    public static readonly ${field} = SqlBaseLexer.${field};`)
  }
  parser = parser.replace('import { Token } from "antlr4ng";', 'import { Token } from "antlr4ng";\nimport { SqlBaseLexer } from "./SqlBaseLexer.js";')
  files["SqlBaseParser.ts"] = parser
}

function header(file) {
  return [
    "// @ts-nocheck",
    "/* eslint-disable */",
    `// GENERATED by scripts/generate-parser.mjs: do not edit. ${file} from Apache Spark ${pin.tag} (${pin.commit}),`,
    `// ${pin.path}, with the actions ported in grammar/port.mjs; antlr-ng ${version("antlr-ng")}, runtime antlr4ng ${version("antlr4ng")}.`,
    "// Licensed under the Apache License, Version 2.0 (grammar/spark/LICENSE); see NOTICE.",
    "",
  ].join("\n")
}

/** Generates into `target`; returns the files' contents by name. */
function generate(target) {
  const work = mkdtempSync(join(tmpdir(), "dbx-grammar-"))
  try {
    for (const file of ["SqlBaseLexer.g4", "SqlBaseParser.g4"]) writeFileSync(join(work, file), ported(file))
    const tool = join(root, "node_modules", "antlr-ng", "dist", "cli", "runner.js")
    const args = ["-Dlanguage=TypeScript", "--generate-listener", "false", "--generate-visitor", "false", "--exact-output-dir", "-o", join(work, "out")]
    // The lexer first: the parser reads its token vocabulary.
    execFileSync(process.execPath, [tool, ...args, join(work, "SqlBaseLexer.g4")], { cwd: work, stdio: ["ignore", "inherit", "inherit"] })
    execFileSync(process.execPath, [tool, ...args, "--lib", join(work, "out"), join(work, "SqlBaseParser.g4")], { cwd: work, stdio: ["ignore", "inherit", "inherit"] })
    const files = {}
    for (const file of FILES) {
      // The tool's own first line names the temporary path; it is replaced by the fixed header.
      const body = readFileSync(join(work, "out", file), "utf8").replace(/^\/\/ Generated from .*\n/, "")
      files[file] = header(file.replace(".ts", ".g4")) + body.replaceAll(work, "<grammar>")
    }
    shareVocabulary(files)
    if (target) for (const [file, text] of Object.entries(files)) writeFileSync(join(target, file), text)
    return files
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
}

if (process.argv.includes("--check")) {
  const fresh = generate()
  const stale = FILES.filter((file) => {
    let committed
    try {
      committed = readFileSync(join(outDir, file), "utf8")
    } catch {
      return true
    }
    return committed !== fresh[file]
  })
  if (stale.length > 0) fail(`src/sql/generated/${stale.join(" and ")} differ from a fresh generation. Run node scripts/generate-parser.mjs and commit the result.`)
  console.log(`src/sql/generated/ matches a fresh generation from Apache Spark ${pin.tag} (${pin.commit.slice(0, 10)}).`)
} else {
  generate(outDir)
  console.log(`generated src/sql/generated/ from Apache Spark ${pin.tag} (${pin.commit.slice(0, 10)}).`)
}
